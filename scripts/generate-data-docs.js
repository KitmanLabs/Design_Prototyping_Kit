#!/usr/bin/env node

const fs = require('fs');
const path = require('path');

// Friendly names for data files
const FILE_NAMES = {
  'athletes.js': 'Athlete profiles, with availability that agrees with the injury records',
  'squads_teams.js': 'Squads and team definitions, counted from the athletes',
  'games_matches.js': "The First Team's recent and upcoming games",
  'training_sessions.js': 'The last week of training sessions, around game days',
  'calendar_events.json': 'Calendar events',
  'injuries_medical.js': 'Medical records and injuries, current and resolved',
  'assessments.js': 'Physical, medical and skills assessments',
  'questionnaires_wellbeing.js': 'Wellbeing and injury recovery questionnaires',
  'users_staff.js': 'Staff and user accounts',
  'club.js': 'The invented club: squads, positions, venues and opponents. Change the club here',
  'roster.js': 'Who is in each squad (used by athletes.js)',
  'clock.js': '"Today" for all generated dates, pinned in builds for the record',
  'fake.js': 'The seeded generators and the nationalities names come from',
  'namePool.js': 'Names per nationality, sampled from faker (generated by scripts/generate-name-pool.mjs)',
  'saved_locations.json': 'Saved venues and locations',
  'forms_templates.json': 'Form templates (medical, wellness, screening)',
  'layout.js': 'Layout constants (navigation, page titles)',
  'messaging.js': 'Messaging and chat data',
  'forms.js': 'Forms pages and drawers: rows, summaries and option lists',
  'athleteViews.js': 'Quick filters, badge colours, tabs and options for the Athletes pages',
  'injuryOptions.js': 'Steps and option lists for the Log injury flow',
  'notifications.js': 'Notifications and category filters for the Notifications queue',
  'settings.js': 'Sections, defaults and option lists for Administration',
  'workloads.js': 'Generated daily training load and availability trend for Squad load and the Overview',
  'calendarEventOptions.js': 'Option lists for the Add game and Add session drawers',
};

// Datasets made by seeded generators rather than written out record by record
const GENERATED = ['athletes.js', 'squads_teams.js', 'games_matches.js', 'training_sessions.js', 'injuries_medical.js', 'assessments.js', 'questionnaires_wellbeing.js', 'users_staff.js', 'workloads.js'];

const DATA_DIR = path.join(__dirname, '../src/data');
const OUTPUT_FILE = path.join(__dirname, '../docs/understanding-the-data.md');

function getFileInfo(filePath) {
  const fileName = path.basename(filePath);
  let recordCount = 'N/A';
  let fields = [];

  try {
    if (filePath.endsWith('.json')) {
      const content = fs.readFileSync(filePath, 'utf8');
      const data = JSON.parse(content);

      if (Array.isArray(data)) {
        recordCount = data.length;
        if (data.length > 0 && typeof data[0] === 'object') {
          fields = Object.keys(data[0]).slice(0, 5); // First 5 fields
        }
      } else if (typeof data === 'object') {
        // For non-array objects, count properties
        fields = Object.keys(data).slice(0, 5);
      }
    } else if (GENERATED.includes(fileName)) {
      recordCount = 'Generated';
    } else if (filePath.endsWith('.js')) {
      // For JS files, just note them as config
      recordCount = 'Config';
    }
  } catch (e) {
    // If we can't parse, that's ok - just skip
  }

  return {
    fileName,
    recordCount,
    fields: fields.join(', ') || '(no fields)',
  };
}

function generateMarkdown() {
  let files = [];

  // Read all files in data directory
  const entries = fs.readdirSync(DATA_DIR);

  entries.forEach((entry) => {
    const filePath = path.join(DATA_DIR, entry);
    const stat = fs.statSync(filePath);

    // Only process JSON and JS files, not subdirectories
    if (stat.isFile() && (entry.endsWith('.json') || entry.endsWith('.js'))) {
      const info = getFileInfo(filePath);
      files.push({
        name: entry,
        friendly: FILE_NAMES[entry] || entry,
        ...info,
      });
    }
  });

  // Sort by filename
  files.sort((a, b) => a.name.localeCompare(b.name));

  // Generate markdown
  const templates = files.find((f) => f.name === 'forms_templates.json');
  const templateCount = templates && typeof templates.recordCount === 'number' ? templates.recordCount : 'several';

  let markdown = `# Understanding the data

<!-- Generated by \`npm run docs:data\` (scripts/generate-data-docs.js). Edit the script, not this page. -->

This prototype has no real server or database. All data lives in local JSON and JavaScript files in \`src/data\`. Think of them like spreadsheets that power the UI. You can ask Claude to add, change, or remove entries in any of these files.

## Generated data

The club's people and records (athletes, staff, squads, injuries, games, training, assessments and questionnaires) aren't written out by hand. Seeded generators make them with [faker](https://fakerjs.dev), so:

- **Everything is invented.** No name, figure or date comes from a real person, a customer or an export. Staff emails use a reserved \`.example\` domain and phone numbers come from the range set aside for fiction.
- **It's the same on every load.** Each dataset has its own seed (\`DATA_SEED\` in \`fake.js\`), so changing one never shifts another.
- **It agrees with itself.** An athlete's availability comes from the injury records, squads count their own athletes, and games only pick athletes who were available that day.
- **Athletes carry iP's availability.** \`availability\` is one of iP's four statuses, which the Playbook's \`AvailabilityLabel\` reads: \`available\`; \`injured\`, shown as Available (Injured/Ill), for an athlete playing through a minor injury; \`returning\`, for an athlete back within the last 14 days; or \`unavailable\`. \`unavailable_since\` is how long the athlete has been in that status, worded as iP sends it ("12 days", or "0 days" when available). The older \`availability_status\` has two values, and its \`Injured\` means out, which is iP's \`unavailable\`, not \`injured\`.
- **It's dated around today.** \`clock.js\` sets "today"; a build for the record pins it, so that version shows the same dates whenever it's opened.

## Data files

| File | What it represents | Records |
|------|-------------------|---------|
`;

  files.forEach((file) => {
    markdown += `| \`${file.name}\` | ${file.friendly} | ${file.recordCount} |\n`;
  });

  markdown += `
## How to change the data

Ask Claude Code to help you:
- **Change the club:** "Give the Women's Team 16 athletes" or "Add an Academy U16 squad" (both in club.js)
- **Change how records are made:** "Make about a quarter of the First Team injured" (injuries_medical.js)
- **Get a different set of people:** "Change the data seed" (fake.js)
- **Change a list:** "Add a Nutrition session type" (training_sessions.js)

Claude handles the formatting. You don't need to edit these files by hand, but you can.

## Form templates

\`forms_templates.json\` lists ${templateCount} form templates (medical screening, wellness checks, training feedback and so on), and \`src/data/formTemplates/\` holds the full question structure for individual templates. Together they define the forms used across the prototype.

## Good to know

- This is **mock data** for prototyping only. It isn't connected to iP: Intelligence Platform or any other Kitman Labs system.
- Your changes only affect this prototype, not the product.
- Asking Claude to make changes keeps the JSON valid.
- Where the data lives and how components use it: [project structure](reference/project-structure.md#data).
`;

  return markdown;
}

try {
  const markdown = generateMarkdown();
  fs.writeFileSync(OUTPUT_FILE, markdown, 'utf8');
  console.log(`✓ Generated ${OUTPUT_FILE}`);
} catch (error) {
  console.error(`Error generating data docs: ${error.message}`);
  process.exit(1);
}
