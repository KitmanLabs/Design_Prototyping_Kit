// Writes src/data/namePool.js: a small, seeded sample of first names and surnames per
// nationality, taken from @faker-js/faker's locale data. The mock data generators draw names
// from this pool with faker's locale-free SimpleFaker, so a prototype's build carries a few
// kilobytes of names instead of faker's full locale files.
//
//   node scripts/generate-name-pool.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { SimpleFaker, de, en, en_AU, es, fr, it, pt_BR } from '@faker-js/faker'

const OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/data/namePool.js')
const FIRST = 40
const LAST = 60

// Where each nationality's names come from. en_GB and en_IE carry no names of their own in
// faker, so British and Irish names come from en_AU's shorter, British-derived lists.
const SOURCES = {
  England: en_AU,
  Ireland: en_AU,
  Spain: es,
  France: fr,
  Germany: de,
  Italy: it,
  Brazil: pt_BR,
  USA: en,
}
// Nationalities whose people usually carry two surnames.
const DOUBLE_SURNAME = ['Spain']

const sampler = new SimpleFaker()
sampler.seed(4271)
const plain = (name) => /^[\p{L}' ]+$/u.test(name) && !name.includes('  ')
const sample = (list, count) => sampler.helpers.shuffle([...new Set(list.filter(plain))]).slice(0, count).sort()

const pool = {}
for (const [country, locale] of Object.entries(SOURCES)) {
  const first = locale.person.first_name
  pool[country] = {
    male: sample(first.male, FIRST),
    female: sample(first.female, FIRST),
    last: sample(locale.person.last_name.generic, LAST),
    ...(DOUBLE_SURNAME.includes(country) && { doubleSurname: true }),
  }
}

const body = `// Generated by scripts/generate-name-pool.mjs from @faker-js/faker's locale data. Don't edit by hand.
// A seeded sample of names per nationality, for the mock data generators (src/data/fake.js).

export const NAME_POOL = ${JSON.stringify(pool, null, 2)}
`
fs.writeFileSync(OUT, body)
console.log(`Wrote ${path.relative(process.cwd(), OUT)}: ${Object.keys(pool).length} nationalities.`)
