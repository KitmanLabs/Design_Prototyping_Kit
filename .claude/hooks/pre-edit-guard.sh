#!/bin/bash
# PreToolUse (Edit|Write|MultiEdit): block edits to generated, secret or vendored files.
# Exit 2 blocks the tool call and shows stderr to Claude.

f=$(jq -r '.tool_input.file_path // empty')

case "$f" in
  */.env | */.env.* | */node_modules/* | */.git/* | */src/playbook-components-build/*)
    echo "BLOCKED: $f must not be edited directly. playbook-components-build is generated by 'npm run strip-flow' from src/playbook-components." >&2
    exit 2
    ;;
esac
exit 0
